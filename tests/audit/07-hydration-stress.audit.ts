/**
 * AUDIT: hydration stress. Cold-loads every route at the three viewports, several pages at a time, and records
 * every page error and console error (React #418 "Hydration failed" in particular), together with enough of the
 * DOM to see what the client rendered differently.
 *   AUDIT_BASE   origin to load (default the local production build on :3200; a `next dev` origin gives full messages)
 *   AUDIT_LOADS  minimum number of cold page loads (default 300)
 *   AUDIT_PARALLEL pages loaded at once (default 6)
 */
import { test } from "@playwright/test";
import { contextOptions, pageRoutes, writeJson, type ViewportName } from "./lib";

test("hydration stress", async ({ browser }) => {
  test.setTimeout(60 * 60_000);
  const base = process.env.AUDIT_BASE || "http://localhost:3200";
  const wanted = Number(process.env.AUDIT_LOADS || 300);
  const parallel = Number(process.env.AUDIT_PARALLEL || 6);
  const routes = pageRoutes.filter((r) => r.group === "marketing" && r.slug !== "workforce").map((r) => r.path);
  const viewports: ViewportName[] = ["desktop", "tablet", "mobile"];
  const jobs: Array<{ route: string; viewport: ViewportName }> = [];
  for (let round = 0; jobs.length < wanted; round++) for (const viewport of viewports) for (const route of routes) jobs.push({ route, viewport });
  const errors: Array<{ route: string; viewport: string; n: number; messages: string[]; clientIds: string[] }> = [];
  const perRoute: Record<string, { loads: number; errors: number }> = {};
  let done = 0;
  const worker = async () => {
    for (;;) {
      const job = jobs.shift();
      if (!job) return;
      const n = ++done;
      const context = await browser.newContext(contextOptions(job.viewport));
      const page = await context.newPage();
      const messages: string[] = [];
      page.on("pageerror", (e) => messages.push("pageerror: " + String(e.message).slice(0, 6000)));
      page.on("console", (m) => { if (m.type() === "error" && !/Failed to load resource/.test(m.text())) messages.push("console: " + m.text().slice(0, 6000)); });
      try {
        await page.goto(base + job.route, { waitUntil: "load", timeout: 90_000 });
        await page.waitForTimeout(900);
      } catch (e) { messages.push("navigation: " + String((e as Error).message).split("\n")[0]); }
      const key = job.route;
      perRoute[key] = perRoute[key] || { loads: 0, errors: 0 };
      perRoute[key].loads += 1;
      if (messages.length) {
        perRoute[key].errors += 1;
        // ids generated by a client-only render look like _r_N_; server-matched ones look like _R_..._
        const clientIds = await page.evaluate(() => Array.from(document.querySelectorAll("[id]")).map((e) => e.id).filter((id) => /^_r_|^:r/.test(id)).slice(0, 8)).catch(() => []);
        errors.push({ route: job.route, viewport: job.viewport, n, messages, clientIds });
      }
      await context.close();
    }
  };
  await Promise.all(Array.from({ length: parallel }, worker));
  const out = { base, loads: done, parallel, loadsWithErrors: errors.length, hydrationErrors: errors.filter((e) => e.messages.some((m) => /#418|Hydration failed|hydrat/i.test(m))).length, perRoute, errors };
  writeJson(`hydration-stress-${process.env.AUDIT_LABEL || "run"}.json`, out);
  console.log(`loads=${out.loads} withErrors=${out.loadsWithErrors} hydration=${out.hydrationErrors}`);
});
